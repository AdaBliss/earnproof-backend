import { createHash } from "crypto";
import { sha256 } from "./hash";
import { safeEqual } from "./timing-safe";

/**
 * Versioned, bounded, secret-redacting hashes of request bodies for
 * sensitive mutations.
 *
 * Why this exists: a high-risk mutation needs audit evidence that binds the
 * approval decision and the later execution to the exact payload the
 * approver reviewed. A bare `sha256(canonicalize(payload))` does not do
 * that on its own — it carries no algorithm version (so an unknown version
 * cannot fail closed), it hashes secret-valued fields verbatim (so a
 * low-entropy secret is brute-forceable from the hash), and it has no size
 * or depth bound.
 *
 * Version 1 — the only version today:
 *   1. Recursively strip fields whose key names a secret (see
 *      {@link isSensitivePayloadKey}); the stripped key paths are reported
 *      in `redactedKeys` so the redaction is observable, never silent.
 *   2. Canonicalize the redacted value: object keys sorted (UTF-16
 *      code-unit order), arrays keep their order, `-0` normalized to `0`.
 *      This is the same canonical form as `canonicalize()` in
 *      `./canonicalize`, restricted by the bounds below.
 *   3. `hash = sha256(canonical)` as lowercase hex (no prefix — the stored
 *      `payloadHash` column keeps its existing bare-hex format; the version
 *      lives in the companion `payloadHashVersion` column).
 *
 * Bounds (fail closed, never truncate silently): maximum nesting depth
 * {@link MAX_REQUEST_BODY_HASH_DEPTH} and maximum canonical length
 * {@link MAX_REQUEST_BODY_CANONICAL_BYTES}. Non-finite numbers, bigints,
 * functions, symbols, and circular structures are rejected — JSON has no
 * unambiguous form for them, and silently coercing them could make
 * distinct payloads collide.
 *
 * Cross-runtime reproducibility: the canonical form is plain JSON with
 * sorted keys and no whitespace, so any runtime with a JSON serializer can
 * reproduce it. Golden vectors generated by an independent Python
 * implementation live in `./testdata/request-body-hash-vectors.v1.json`
 * (generator: `scripts/generate-request-body-hash-vectors.py`) and are
 * asserted in `request-body-hash.spec.ts`.
 *
 * Compatibility: the raw payload is still stored as before — execution
 * reads the stored payload, so storage is unchanged. Only the *hash input*
 * excludes secrets, and only for hashes computed by this module.
 */

/** Current payload-hash version. Bump when the canonicalization or digest changes. */
export const CURRENT_PAYLOAD_HASH_VERSION = 1;

/** Versions {@link verifyRequestBodyHash} accepts. Anything else fails closed. */
export const SUPPORTED_PAYLOAD_HASH_VERSIONS: readonly number[] = [
  CURRENT_PAYLOAD_HASH_VERSION,
];

/** Maximum nesting depth of a payload (root counts as depth 1). */
export const MAX_REQUEST_BODY_HASH_DEPTH = 32;

/** Maximum length, in bytes, of the canonical JSON that gets hashed. */
export const MAX_REQUEST_BODY_CANONICAL_BYTES = 1_048_576;

/** A stored payload hash plus the version that produced it. */
export interface StoredPayloadHash {
  /** Version recorded alongside the hash; rows predating versioning carry 1. */
  payloadHashVersion?: number | null;
  payloadHash: string;
}

/** Result of hashing a request body. */
export interface RequestBodyHash {
  version: number;
  /** Lowercase hex SHA-256 of the canonical redacted payload. */
  hash: string;
  /** Length in bytes of the canonical form that was hashed. */
  canonicalLength: number;
  /** Sorted dot-paths of the secret-bearing keys stripped before hashing. */
  redactedKeys: string[];
}

/** Raised when a caller asks for a payload-hash version this code does not know. */
export class UnsupportedPayloadHashVersionError extends Error {
  constructor(version: number) {
    super(`Unsupported request body hash version: ${version}`);
    this.name = "UnsupportedPayloadHashVersionError";
  }
}

/** Raised when the canonical form exceeds the size bound. */
export class RequestBodyTooLargeError extends Error {
  constructor(canonicalLength: number) {
    super(
      `Canonical request body is ${canonicalLength} bytes, exceeding the limit of ${MAX_REQUEST_BODY_CANONICAL_BYTES} bytes`,
    );
    this.name = "RequestBodyTooLargeError";
  }
}

/** Raised when a value has no unambiguous canonical JSON form. */
export class UncanonicalizableRequestBodyError extends TypeError {
  constructor(detail: string) {
    super(`Cannot canonicalize request body: ${detail}`);
    this.name = "UncanonicalizableRequestBodyError";
  }
}

// Key-name rules for secret-bearing fields. Keys are matched after
// lowercasing and stripping `_`/`-` separators, so `apiKey`, `api_key`,
// and `API-KEY` all match. Deliberately narrow: names such as `amount`,
// `address`, or `tokenId` are *not* secrets and stay in the hash, so the
// approver-reviewed parameters keep binding the decision.
const SENSITIVE_KEY_PATTERNS: readonly RegExp[] = [
  /secret/,
  /password|passwd/,
  /privatekey/,
  /apikey/,
  /accesstoken/,
  /authtoken/,
  /bearer/,
  /credential/,
  /signingkey/,
  /encryptionkey/,
  /seedphrase/,
  /mnemonic/,
];

/**
 * True when a payload key names a secret-bearing field. A key is sensitive
 * when it matches a secret pattern, or when it is exactly `token` or ends
 * in `token` (`authToken`, `refreshToken`, `executionLeaseToken`) — a
 * bearer value. `tokenId` and friends do not match: they name an
 * identifier, not a bearer secret.
 */
export function isSensitivePayloadKey(key: string): boolean {
  const normalized = key.toLowerCase().replace(/[_-]/g, "");
  if (normalized === "token" || normalized.endsWith("token")) return true;
  return SENSITIVE_KEY_PATTERNS.some((pattern) => pattern.test(normalized));
}

/**
 * Recursively strip secret-bearing keys from a value. Arrays keep their
 * order and are traversed; objects are copied without their sensitive keys.
 * Returns the redacted value plus the sorted dot-paths that were stripped.
 * The input is never mutated.
 */
export function redactSensitivePayloadKeys(value: unknown): {
  value: unknown;
  redactedKeys: string[];
} {
  const redactedKeys: string[] = [];
  const redacted = redactValue(value, "", redactedKeys, 1, new Set());
  return { value: redacted, redactedKeys: redactedKeys.sort() };
}

function redactValue(
  value: unknown,
  path: string,
  redactedKeys: string[],
  depth: number,
  seen: Set<object>,
): unknown {
  if (depth > MAX_REQUEST_BODY_HASH_DEPTH) {
    throw new UncanonicalizableRequestBodyError(
      `nesting exceeds the maximum depth of ${MAX_REQUEST_BODY_HASH_DEPTH}`,
    );
  }
  if (Array.isArray(value)) {
    if (seen.has(value)) {
      throw new UncanonicalizableRequestBodyError("circular structure");
    }
    seen.add(value);
    try {
      return value.map((item, index) =>
        redactValue(
          item,
          path ? `${path}[${index}]` : `[${index}]`,
          redactedKeys,
          depth + 1,
          seen,
        ),
      );
    } finally {
      seen.delete(value);
    }
  }
  if (value !== null && typeof value === "object") {
    if (seen.has(value)) {
      throw new UncanonicalizableRequestBodyError("circular structure");
    }
    seen.add(value);
    try {
      const out: Record<string, unknown> = {};
      for (const [key, child] of Object.entries(value as Record<string, unknown>)) {
        const childPath = path ? `${path}.${key}` : key;
        if (isSensitivePayloadKey(key)) {
          redactedKeys.push(childPath);
          continue;
        }
        out[key] = redactValue(child, childPath, redactedKeys, depth + 1, seen);
      }
      return out;
    } finally {
      seen.delete(value);
    }
  }
  return value;
}

/**
 * Canonical form of a request body for the given hash version: secrets
 * redacted, then key-sorted JSON with no whitespace. Throws
 * {@link UnsupportedPayloadHashVersionError} for unknown versions,
 * {@link RequestBodyTooLargeError} when the canonical form exceeds the size
 * bound, and {@link UncanonicalizableRequestBodyError} for values with no
 * unambiguous JSON form.
 */
export function canonicalizeRequestBody(
  payload: unknown,
  version: number = CURRENT_PAYLOAD_HASH_VERSION,
): string {
  assertSupportedVersion(version);
  const { value } = redactSensitivePayloadKeys(payload);
  return canonicalizeSorted(value);
}

/**
 * Hash a request body under the given version. Returns the version, the
 * bare-hex SHA-256 of the canonical redacted form, its byte length, and the
 * redacted key paths.
 */
export function hashRequestBody(
  payload: unknown,
  version: number = CURRENT_PAYLOAD_HASH_VERSION,
): RequestBodyHash {
  assertSupportedVersion(version);
  const { value, redactedKeys } = redactSensitivePayloadKeys(payload);
  const canonical = canonicalizeSorted(value);
  return {
    version,
    hash: sha256(canonical),
    canonicalLength: Buffer.byteLength(canonical, "utf8"),
    redactedKeys,
  };
}

function assertSupportedVersion(version: number): void {
  if (version !== CURRENT_PAYLOAD_HASH_VERSION) {
    throw new UnsupportedPayloadHashVersionError(version);
  }
}

/** Key-sorted JSON with no whitespace, enforcing the size bound. */
function canonicalizeSorted(value: unknown): string {
  const canonical = JSON.stringify(sortValue(value, 1, new Set()));
  const length = Buffer.byteLength(canonical, "utf8");
  if (length > MAX_REQUEST_BODY_CANONICAL_BYTES) {
    throw new RequestBodyTooLargeError(length);
  }
  return canonical;
}

/**
 * Verify that `stored` is the hash of `payload` under its recorded version.
 * Returns false on any mismatch. Throws
 * {@link UnsupportedPayloadHashVersionError} when the stored version is
 * unknown — fail closed, never treat an unrecognized version as a match.
 * The comparison is constant-time for equal-length hex strings.
 *
 * @param allowLegacyUnredacted — only for rows written before redaction
 *   existed: also accept the hash of the *unredacted* canonical payload
 *   (the pre-change `sha256(canonicalize(payload))`). New rows never need
 *   this; pass it only when re-verifying a stored row, never when creating
 *   a hash.
 */
export function verifyRequestBodyHash(
  stored: StoredPayloadHash,
  payload: unknown,
  options: { allowLegacyUnredacted?: boolean } = {},
): boolean {
  const version = stored.payloadHashVersion ?? CURRENT_PAYLOAD_HASH_VERSION;
  if (!SUPPORTED_PAYLOAD_HASH_VERSIONS.includes(version)) {
    throw new UnsupportedPayloadHashVersionError(version);
  }
  const current = hashRequestBody(payload, version);
  if (safeEqual(current.hash, stored.payloadHash)) return true;
  if (options.allowLegacyUnredacted) {
    // Pre-redaction rows hashed the raw payload. Accept that exact legacy
    // form so execution of requests approved before this change keeps
    // working; the redacted form is tried first and wins for all new rows.
    const legacy = createHash("sha256")
      .update(canonicalizeLegacy(payload))
      .digest("hex");
    return safeEqual(legacy, stored.payloadHash);
  }
  return false;
}

/** Pre-change canonicalization (`canonicalize()` + JSON.stringify) for legacy verification only. */
function canonicalizeLegacy(value: unknown): string {
  return JSON.stringify(sortValue(value, 1, new Set()));
}

function sortValue(
  value: unknown,
  depth: number,
  seen: Set<object>,
): unknown {
  if (depth > MAX_REQUEST_BODY_HASH_DEPTH) {
    throw new UncanonicalizableRequestBodyError(
      `nesting exceeds the maximum depth of ${MAX_REQUEST_BODY_HASH_DEPTH}`,
    );
  }
  if (typeof value === "number") {
    if (!Number.isFinite(value)) {
      throw new UncanonicalizableRequestBodyError(
        `non-finite number: ${String(value)}`,
      );
    }
    // JSON.stringify(-0) is "0", but normalize explicitly so the canonical
    // form does not depend on that quirk (other runtimes print "-0.0").
    return Object.is(value, -0) ? 0 : value;
  }
  if (typeof value === "bigint") {
    throw new UncanonicalizableRequestBodyError("bigint has no JSON form");
  }
  if (typeof value === "function" || typeof value === "symbol") {
    throw new UncanonicalizableRequestBodyError(
      `value of type ${typeof value} has no JSON form`,
    );
  }
  if (value === undefined) {
    // Matches JSON.stringify: dropped from objects, null in arrays.
    return undefined;
  }
  if (Array.isArray(value)) {
    if (seen.has(value)) {
      throw new UncanonicalizableRequestBodyError("circular structure");
    }
    seen.add(value);
    try {
      return value.map((item) =>
        item === undefined ? null : sortValue(item, depth + 1, seen),
      );
    } finally {
      seen.delete(value);
    }
  }
  if (value !== null && typeof value === "object") {
    if (value instanceof Date) return value.toISOString();
    if (seen.has(value)) {
      throw new UncanonicalizableRequestBodyError("circular structure");
    }
    seen.add(value);
    try {
      const sorted: Record<string, unknown> = {};
      for (const key of Object.keys(value as Record<string, unknown>).sort()) {
        const child = (value as Record<string, unknown>)[key];
        if (child !== undefined) {
          sorted[key] = sortValue(child, depth + 1, seen);
        }
      }
      return sorted;
    } finally {
      seen.delete(value);
    }
  }
  return value;
}
